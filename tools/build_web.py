"""Bundle web/index.html + web/face.js into a gzipped C array (src/webui_html.h).

Runs automatically before every PlatformIO build (extra_scripts = pre:...),
or by hand:  python tools/build_web.py
"""
import gzip, os, sys

def build(root):
    web = os.path.join(root, "web")
    html = open(os.path.join(web, "index.html"), encoding="utf-8").read()
    face = open(os.path.join(web, "face.js"), encoding="utf-8").read()
    if "/*@FACE_JS@*/" not in html:
        sys.exit("web/index.html is missing the /*@FACE_JS@*/ placeholder")
    page = html.replace("/*@FACE_JS@*/", face).encode("utf-8")
    gz = gzip.compress(page, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    out = (
        "#pragma once\n"
        "// GENERATED by tools/build_web.py from web/index.html + web/face.js — edit those, not this.\n"
        "#include <Arduino.h>\n"
        f"static const size_t INDEX_HTML_GZ_LEN = {len(gz)};\n"
        "static const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n"
    )
    dst = os.path.join(root, "src", "webui_html.h")
    if not os.path.exists(dst) or open(dst, encoding="utf-8").read() != out:
        open(dst, "w", encoding="utf-8").write(out)
    print(f"web page: {len(page)} bytes -> {len(gz)} gzipped")

try:
    Import("env")  # noqa: F821  (PlatformIO)
    build(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    build(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
